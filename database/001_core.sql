-- PostgreSQL 18. Run once in an empty application database as its owner.
BEGIN;
SET LOCAL TIME ZONE 'UTC';

CREATE TABLE marketplace_settings (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    unanswered_order_timeout interval NOT NULL DEFAULT interval '48 hours'
        CHECK (unanswered_order_timeout > interval '0'),
    refresh_timezone varchar(80) NOT NULL DEFAULT 'Asia/Shanghai'
);
-- Explicit course-demo default; choose the deployment currency before creating revisions.
INSERT INTO marketplace_settings(singleton,currency) VALUES(true,'USD');

CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL CHECK (email = btrim(email) AND position('@' IN email) > 1),
    password varchar(128) NOT NULL, -- Django encoded hash; never plaintext
    full_name varchar(150) NOT NULL CHECK (length(btrim(full_name)) > 0),
    location varchar(150), private_contact varchar(100),
    status varchar(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active','blocked','deactivated')),
    is_active boolean NOT NULL DEFAULT true, -- authentication enabled; separate from marketplace blocking
    is_staff boolean NOT NULL DEFAULT false, is_superuser boolean NOT NULL DEFAULT false,
    last_login timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), deactivated_at timestamptz,
    CHECK ((status = 'deactivated') = (deactivated_at IS NOT NULL))
);
CREATE UNIQUE INDEX users_email_ci_uq ON users (lower(email));

-- Reference bootstrap for Django auth. Use these exact db_table mappings in migrations.
CREATE TABLE django_content_type (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_label varchar(100) NOT NULL, model varchar(100) NOT NULL, UNIQUE (app_label,model)
);
CREATE TABLE auth_permission (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL, content_type_id integer NOT NULL REFERENCES django_content_type(id),
    codename varchar(100) NOT NULL, UNIQUE (content_type_id,codename)
);
CREATE TABLE auth_group (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(150) NOT NULL UNIQUE
);
CREATE TABLE auth_group_permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id integer NOT NULL REFERENCES auth_group(id),
    permission_id integer NOT NULL REFERENCES auth_permission(id), UNIQUE(group_id,permission_id)
);
CREATE TABLE users_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(user_id), group_id integer NOT NULL REFERENCES auth_group(id),
    UNIQUE(user_id,group_id)
);
CREATE TABLE users_user_permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(user_id),
    permission_id integer NOT NULL REFERENCES auth_permission(id), UNIQUE(user_id,permission_id)
);
CREATE TABLE django_session (
    session_key varchar(40) PRIMARY KEY, session_data text NOT NULL, expire_date timestamptz NOT NULL
);
CREATE INDEX django_session_expiry_idx ON django_session(expire_date);
CREATE INDEX users_groups_group_idx ON users_groups(group_id,user_id);
CREATE INDEX auth_group_permissions_permission_idx ON auth_group_permissions(permission_id);
CREATE INDEX users_permissions_permission_idx ON users_user_permissions(permission_id);

CREATE TABLE categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (length(btrim(name)) > 0),
    description text NOT NULL DEFAULT '', is_active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX categories_name_ci_uq ON categories(lower(name));

CREATE TABLE products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id bigint NOT NULL REFERENCES users(user_id), current_revision_no integer,
    availability varchar(16) NOT NULL DEFAULT 'draft'
        CHECK (availability IN ('draft','available','reserved','sold')),
    visibility varchar(24) NOT NULL DEFAULT 'visible'
        CHECK (visibility IN ('visible','removed_by_seller','removed_by_admin')),
    context_version bigint NOT NULL DEFAULT 0 CHECK (context_version >= 0),
    first_published_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (availability = 'draft' OR (current_revision_no IS NOT NULL AND first_published_at IS NOT NULL))
);
CREATE TABLE product_revisions (
    product_id bigint NOT NULL REFERENCES products(product_id),
    revision_no integer NOT NULL CHECK (revision_no > 0),
    category_id bigint NOT NULL REFERENCES categories(category_id),
    title varchar(200) NOT NULL CHECK (length(btrim(title)) > 0),
    description text NOT NULL CHECK (length(description) BETWEEN 1 AND 20000),
    price numeric(12,2) NOT NULL CHECK (price > 0 AND price <> 'NaN'::numeric),
    original_price numeric(12,2) CHECK (original_price >= 0 AND original_price <> 'NaN'::numeric),
    currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    condition varchar(16) NOT NULL CHECK (condition IN ('like_new','good','fair','poor')),
    location varchar(150) NOT NULL CHECK (length(btrim(location)) > 0),
    text_fingerprint varchar(64) NOT NULL CHECK (text_fingerprint ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_xid xid8 NOT NULL DEFAULT pg_current_xact_id(),
    PRIMARY KEY (product_id,revision_no)
);
ALTER TABLE products ADD CONSTRAINT products_current_revision_fk
    FOREIGN KEY(product_id,current_revision_no) REFERENCES product_revisions(product_id,revision_no)
    DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE product_images (
    image_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL, revision_no integer NOT NULL,
    storage_key varchar(500) NOT NULL UNIQUE,
    sort_order smallint NOT NULL CHECK (sort_order BETWEEN 0 AND 5),
    content_type varchar(32) NOT NULL CHECK (content_type IN ('image/jpeg','image/png','image/webp')),
    byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 5242880),
    content_sha256 char(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    width integer NOT NULL CHECK (width > 0), height integer NOT NULL CHECK (height > 0),
    uploaded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY(product_id,revision_no) REFERENCES product_revisions(product_id,revision_no),
    UNIQUE(product_id,revision_no,sort_order)
);

CREATE TABLE conversations (
    conversation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products(product_id),
    buyer_id bigint NOT NULL REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(product_id,buyer_id)
);
CREATE TABLE chat_messages (
    message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversations(conversation_id),
    sender_id bigint NOT NULL REFERENCES users(user_id),
    message_text text NOT NULL CHECK (length(btrim(message_text)) BETWEEN 1 AND 4000),
    sent_at timestamptz NOT NULL DEFAULT clock_timestamp(), read_at timestamptz,
    CHECK (read_at IS NULL OR read_at >= sent_at)
);

CREATE TABLE transactions (
    transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL, revision_no integer NOT NULL,
    buyer_id bigint NOT NULL REFERENCES users(user_id),
    status varchar(16) NOT NULL DEFAULT 'placed'
        CHECK (status IN ('placed','accepted','shipped','disputed','completed','cancelled')),
    request_key uuid NOT NULL, request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY(product_id,revision_no) REFERENCES product_revisions(product_id,revision_no),
    UNIQUE(buyer_id,request_key), UNIQUE(transaction_id,product_id,revision_no,buyer_id)
);
CREATE UNIQUE INDEX transactions_one_sale_uq ON transactions(product_id) WHERE status <> 'cancelled';
CREATE TABLE order_status_history (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id bigint NOT NULL REFERENCES transactions(transaction_id),
    from_status varchar(16) CHECK (from_status IN ('placed','accepted','shipped','disputed','completed','cancelled')),
    to_status varchar(16) NOT NULL CHECK (to_status IN ('placed','accepted','shipped','disputed','completed','cancelled')),
    actor_id bigint REFERENCES users(user_id), system_actor varchar(40), reason text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((actor_id IS NULL) <> (system_actor IS NULL)),
    CHECK (from_status IS DISTINCT FROM to_status)
);

CREATE TABLE fraud_reports (
    report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL, revision_no integer NOT NULL,
    reporter_id bigint NOT NULL REFERENCES users(user_id), transaction_id bigint,
    reason_code varchar(32) NOT NULL CHECK (reason_code IN ('misleading_description','suspicious_price','duplicate_listing','non_delivery','counterfeit','other')),
    comment text NOT NULL CHECK (length(btrim(comment)) BETWEEN 1 AND 5000),
    status varchar(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','reviewing','resolved','dismissed')),
    assigned_admin_id bigint REFERENCES users(user_id), public_outcome text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), resolved_at timestamptz,
    FOREIGN KEY(product_id,revision_no) REFERENCES product_revisions(product_id,revision_no),
    FOREIGN KEY(transaction_id,product_id,revision_no,reporter_id)
        REFERENCES transactions(transaction_id,product_id,revision_no,buyer_id),
    UNIQUE(report_id,product_id,revision_no),
    CHECK ((status IN ('resolved','dismissed')) = (resolved_at IS NOT NULL))
);
CREATE TABLE report_attachments (
    attachment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id bigint NOT NULL REFERENCES fraud_reports(report_id),
    storage_key varchar(500) NOT NULL UNIQUE,
    sort_order smallint NOT NULL CHECK (sort_order BETWEEN 0 AND 2),
    content_type varchar(32) NOT NULL CHECK (content_type IN ('image/jpeg','image/png','image/webp')),
    byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 5242880),
    content_sha256 char(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    uploaded_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(report_id,sort_order)
);
CREATE TABLE moderation_reviews (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL, revision_no integer NOT NULL, report_id bigint,
    reviewer_id bigint NOT NULL REFERENCES users(user_id),
    verdict varchar(16) NOT NULL CHECK (verdict IN ('fraud','legitimate','unresolved')),
    reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    evidence_summary text NOT NULL CHECK (length(btrim(evidence_summary)) > 0),
    supersedes_review_id bigint UNIQUE,
    reviewed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY(product_id,revision_no) REFERENCES product_revisions(product_id,revision_no),
    FOREIGN KEY(report_id,product_id,revision_no) REFERENCES fraud_reports(report_id,product_id,revision_no),
    UNIQUE(review_id,product_id,revision_no),
    FOREIGN KEY(supersedes_review_id,product_id,revision_no) REFERENCES moderation_reviews(review_id,product_id,revision_no),
    CHECK (supersedes_review_id IS NULL OR supersedes_review_id <> review_id)
);
CREATE UNIQUE INDEX moderation_one_root_uq ON moderation_reviews(product_id,revision_no) WHERE supersedes_review_id IS NULL;
CREATE TABLE admin_audit_logs (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id bigint NOT NULL REFERENCES users(user_id), action_type varchar(64) NOT NULL,
    user_id bigint REFERENCES users(user_id), product_id bigint REFERENCES products(product_id),
    report_id bigint REFERENCES fraud_reports(report_id), review_id bigint REFERENCES moderation_reviews(review_id),
    transaction_id bigint REFERENCES transactions(transaction_id), model_id bigint, ruleset_id bigint, dataset_id bigint,
    reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    before_data jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(before_data) = 'object'),
    after_data jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(after_data) = 'object'),
    occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (num_nonnulls(user_id,product_id,report_id,review_id,transaction_id,model_id,ruleset_id,dataset_id) >= 1)
);

-- P1 extension structures. Their UI/workflows remain optional.
CREATE TABLE seller_appeals (
    appeal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id bigint NOT NULL REFERENCES moderation_reviews(review_id),
    seller_id bigint NOT NULL REFERENCES users(user_id), reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    status varchar(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','reviewing','upheld','corrected','withdrawn')),
    assigned_admin_id bigint REFERENCES users(user_id), outcome text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), resolved_at timestamptz,
    CHECK ((status IN ('upheld','corrected','withdrawn')) = (resolved_at IS NOT NULL))
);
CREATE UNIQUE INDEX seller_appeals_one_open_uq ON seller_appeals(review_id) WHERE status IN ('pending','reviewing');
CREATE TABLE notifications (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL REFERENCES users(user_id), source_event_key varchar(200) NOT NULL,
    summary varchar(500) NOT NULL, product_id bigint REFERENCES products(product_id),
    transaction_id bigint REFERENCES transactions(transaction_id), report_id bigint REFERENCES fraud_reports(report_id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), read_at timestamptz,
    UNIQUE(recipient_id,source_event_key), CHECK (read_at IS NULL OR read_at >= created_at)
);

