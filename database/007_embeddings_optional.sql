BEGIN;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE embedding_models (
    embedding_model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(120) NOT NULL UNIQUE,
    model_name TEXT NOT NULL,
    model_revision TEXT NOT NULL,
    dimensions INTEGER NOT NULL DEFAULT 384 CHECK (dimensions=384),
    text_policy TEXT NOT NULL,
    dependency_manifest JSONB NOT NULL CHECK (jsonb_typeof(dependency_manifest)='object'),
    registered_by BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE review_embedding (
    review_embedding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES moderation_reviews(review_id) ON DELETE RESTRICT,
    embedding_model_id BIGINT NOT NULL REFERENCES embedding_models ON DELETE RESTRICT,
    content_sha256 CHAR(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    embedding VECTOR(384) NOT NULL CHECK (vector_norm(embedding)>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(review_id, embedding_model_id)
);
CREATE INDEX review_embedding_model_idx ON review_embedding(embedding_model_id,review_id);
CREATE TRIGGER embedding_models_immutable BEFORE UPDATE OR DELETE ON embedding_models FOR EACH ROW EXECUTE FUNCTION reject_risk_history_change();
CREATE TRIGGER review_embedding_immutable BEFORE UPDATE OR DELETE ON review_embedding FOR EACH ROW EXECUTE FUNCTION reject_risk_history_change();
COMMENT ON TABLE review_embedding IS 'Optional administrator-only semantic retrieval over immutable moderation reviews. No public ratings/reviews feature is implied, and embeddings are not P0 Random Forest features.';
COMMENT ON COLUMN embedding_models.text_policy IS 'Version the exact permitted text fields, redaction and normalization. Exclude raw private attachments, messages and contact details.';
COMMENT ON COLUMN embedding_models.dimensions IS 'This optional migration deliberately fixes 384 dimensions. A different dimension requires an explicit new migration and compatible indexes.';

REVOKE ALL ON embedding_models,review_embedding FROM PUBLIC;
